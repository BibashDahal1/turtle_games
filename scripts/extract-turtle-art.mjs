#!/usr/bin/env node
/**
 * Reads your ORIGINAL loader HTML and writes lib/turtleArt.ts from it.
 *
 *   node scripts/extract-turtle-art.mjs path/to/original-loader.html
 *
 * It pulls out `const COLS = [...]` and `const DATA = [...]` exactly as they are,
 * so nothing has to be copy-pasted by hand.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";

const input = process.argv[2];
if (!input) {
  console.error(
    "Usage: node scripts/extract-turtle-art.mjs <original-loader.html>",
  );
  process.exit(1);
}

const html = readFileSync(resolve(input), "utf8");

const colsMatch = html.match(/const\s+COLS\s*=\s*(\[[\s\S]*?\])\s*;/);
const dataMatch = html.match(
  /const\s+DATA\s*=\s*(\[[\s\S]*?\])\s*;\s*const\s+W2/,
);

if (!colsMatch || !dataMatch) {
  console.error(
    "Could not find `const COLS = [...]` and `const DATA = [...]` (followed by `const W2`) in that file.",
  );
  process.exit(1);
}

// The arrays are plain literals (strings + numbers), so evaluating them is safe here.
const COLS = new Function(`return ${colsMatch[1]}`)();
const DATA = new Function(`return ${dataMatch[1]}`)();

const ok =
  Array.isArray(COLS) &&
  COLS.every((c) => typeof c === "string") &&
  Array.isArray(DATA) &&
  DATA.length > 0 &&
  DATA.every(
    (e) =>
      Array.isArray(e) &&
      Number.isInteger(e[0]) &&
      typeof e[1] === "string" &&
      COLS[e[0]],
  );

if (!ok) {
  console.error("COLS / DATA were found but don't have the expected shape.");
  process.exit(1);
}

const out = `/* AUTO-GENERATED by scripts/extract-turtle-art.mjs from the original loader HTML. */
export const COLS: string[] = ${JSON.stringify(COLS)};

export const DATA: [number, string][] = [
${DATA.map((e) => "  " + JSON.stringify(e)).join(",\n")},
];
`;

const target = resolve("lib/turtleArt.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(
  `lib/turtleArt.ts written: ${COLS.length} colours, ${DATA.length} colour layers.`,
);
